#!/usr/bin/env node
/**
 * Generates the Ed25519 catalog signing key (spec §5.4). The private seed goes to the macOS Keychain only;
 * the public key is written to packages/core/src/catalog/publicKey.ts and committed.
 *
 *   node scripts/gen-catalog-key.mjs            # refuses to overwrite an existing key
 *   node scripts/gen-catalog-key.mjs --rotate   # new key; every manifest must be re-signed (scripts/sign-catalog.mjs)
 */
import { execFileSync } from "node:child_process";
import { generateKeyPairSync } from "node:crypto";
import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

export const KC_SERVICE = "inborn-catalog-signing";
export const KC_ACCOUNT = "ed25519-v1";
const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const publicKeyFile = path.join(repoRoot, "packages/core/src/catalog/publicKey.ts");

export function kcGet() {
  try {
    return execFileSync("security", ["find-generic-password", "-s", KC_SERVICE, "-a", KC_ACCOUNT, "-w"], { stdio: ["ignore", "pipe", "ignore"] })
      .toString()
      .trim();
  } catch {
    return null;
  }
}

function kcSet(seedHex) {
  execFileSync("security", ["add-generic-password", "-U", "-s", KC_SERVICE, "-a", KC_ACCOUNT, "-w", seedHex], { stdio: "ignore" });
}

/* Node emits DER; Ed25519 raw keys are the trailing 32 bytes of both PKCS#8 (seed) and SPKI (public key). */
function generate() {
  const { privateKey, publicKey } = generateKeyPairSync("ed25519");
  const seed = privateKey.export({ type: "pkcs8", format: "der" }).subarray(-32);
  const pub = publicKey.export({ type: "spki", format: "der" }).subarray(-32);
  return { seedHex: seed.toString("hex"), publicHex: pub.toString("hex") };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const rotate = process.argv.includes("--rotate");
  if (kcGet() && !rotate) {
    console.error(`a key already exists in the Keychain (${KC_SERVICE}); pass --rotate to replace it`);
    process.exit(1);
  }
  const { seedHex, publicHex } = generate();
  kcSet(seedHex);
  writeFileSync(
    publicKeyFile,
    `/** Ed25519 public key of the catalog publisher (generated by scripts/gen-catalog-key.mjs; the private key lives in the macOS Keychain). */\nexport const CATALOG_PUBLIC_KEY = "${publicHex}";\n`,
  );
  console.log(`private seed stored in Keychain ${KC_SERVICE}/${KC_ACCOUNT} (${seedHex.slice(0, 6)}…)`);
  console.log(`public key ${publicHex} -> ${path.relative(repoRoot, publicKeyFile)}`);
}
